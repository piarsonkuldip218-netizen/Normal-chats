/** Returns translated title + description for the given service slug. */
export function useService(slug: string): ServiceCopy {
  const { locale } = useT();
  return servicesT[locale]?.[slug] ?? servicesT.en[slug];
}

/** Returns full translated tech equipment copy. */
export function useTech(slug: string): TechCopy {
  const { locale } = useT();
  return techT[locale]?.[slug] ?? techT.en[slug];
}

/** Returns translated feature card copy by index. */
export function useFeature(index: number): FeatureCopy {
  const { locale } = useT();
  const key = String(index);
  return featuresT[locale]?.[key] ?? featuresT.en[key];
}

/** Returns translated gallery caption + category by index. */
export function useGalleryPhoto(index: number): GalleryCopy {
  const { locale } = useT();
  const key = String(index);
  return galleryT[locale]?.[key] ?? galleryT.en[key];
}

/** Returns the doctor's bio in the active locale. */
export function useDoctorBio(): string {
  const { locale } = useT();
  return doctorBio[locale] ?? doctorBio.en;
}
